/* ============ SEEDED RNG (déterministe par date + signe) ============ */
function hashStr(s) {
  let h = 2166136261;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

function mulberry32(seed) {
  let a = seed;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function pick(rng, arr) {
  return arr[Math.floor(rng() * arr.length)];
}

function range(rng, min, max) {
  return Math.round(min + rng() * (max - min));
}

export function todayISO() {
  const d = new Date();
  return d.getFullYear() + "-" + String(d.getMonth() + 1).padStart(2, "0") + "-" + String(d.getDate()).padStart(2, "0");
}

export function signFromBirthdate(m, d) {
  for (const s of SIGNS) {
    const b = s.debut, f = s.fin;
    if (b[0] <= f[0]) {
      if ((m === b[0] && d >= b[1]) || (m === f[0] && d <= f[1]) || (m > b[0] && m < f[0])) return s.key;
    } else {
      if ((m === b[0] && d >= b[1]) || (m === f[0] && d <= f[1]) || m > b[0] || m < f[0]) return s.key;
    }
  }
  return SIGNS[0].key;
}

export function findSign(key) {
  return SIGNS.find((s) => s.key === key) || SIGNS[0];
}

